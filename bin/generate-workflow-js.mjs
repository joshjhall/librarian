#!/usr/bin/env node
// Generate the enrolled workflow.js harnesses from their editable fragments (#806).
//
// WHY A BUILD STEP AT ALL. The Workflow engine parses a workflow.js as a
// SCRIPT, not a module, so no import spelling works — #712 probed all three
// (static import is read as the dynamic call form, the dynamic form is
// explicitly disabled, and hoisting an import above `export const meta` trips
// the meta-must-be-first rule). A sibling-module split is therefore impossible,
// which is what #712 declined. Concatenation sidesteps the ban entirely: the
// sources are ordinary files, and the ARTIFACT contains no import even though
// it was assembled from several. The engine only ever sees the artifact.
//
// WHY PURE BYTE-CONCATENATION. The artifact is the exact byte concatenation of
// its fragments in manifest order — no template, no codegen, no reformatting.
// That is what makes the "generation is faithful" property (#806 AC3) true by
// CONSTRUCTION rather than by careful transcription: cutting a file into slices
// and re-joining them cannot alter the bytes, so the first generation is
// necessarily a no-op diff, and any later drift is a real change rather than a
// generator artifact. It also means a fragment edit is exactly as predictable
// as editing the artifact in place used to be.
//
// WHY THE ARTIFACT STAYS COMMITTED. marketplace.json sources each plugin from
// ./plugins/<name> and `claude plugin install` copies the tree as-is — there is
// no build hook anywhere in the install path. Generation is a repo-authoring
// step; the generated bytes ship. That is also why freshness cannot be tied to
// PR push: the harness runs on EVERY local /workflow:ship-issue review cycle,
// including runs that never open a PR, so a PR-tied generator would let a local
// fragment edit silently run stale bytes. tests/lint-workflow-js-generated.sh
// is the gate that makes staleness fail loudly, locally and in CI.
//
// ORDER IS LOAD-BEARING, so the manifest is EXPLICIT and never a glob. In
// ship-issue's harness the `scope-drift` entry of NEW_DIMENSIONS calls
// `sanitize(issue.title)` at module load; emitting that fragment before the one
// declaring `sanitize` throws a temporal-dead-zone error — but only on the
// branch where `issue` is truthy, which is invisible to any test that extracts
// without an issue. That is the #260 regression exactly. The manifest is the
// same shape, and exists for the same reason, as tests/lib/fragments.sh's
// ordered list: it fails when a fragment on disk is unlisted OR a listed one is
// missing, in both directions, so a fragment cannot join or leave the build
// quietly.
//
// Usage:
//   node bin/generate-workflow-js.mjs [--check] [harness ...]
//
//   (no args)  regenerate every enrolled harness, writing the artifacts
//   --check    compare instead of writing; exit non-zero on drift or on any
//              manifest violation. This is the freshness gate's entry point.
//   harness    limit the run to the named enrolled harness(es), by artifact
//              path or by the trailing skill/agent directory name.
//
// Exit codes: 0 = clean, 1 = drift or manifest violation, 2 = usage error.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// bin/ -> repo root.
const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// ENROLLED HARNESSES (#806 AC7). A harness enrolls when it exceeds the js
// `high` production-LOC budget in check-decomposition/thresholds.yml (800).
// Measured 2026-08-25: ship-issue 916 and codebase-audit 803 are over it;
// orchestrate 797 and code-reviewer 670 are over the `warn` budget only, and
// rebase-agent 331 / ci-fixer 310 are comfortably under. The four short ones
// would pay the build step's ceremony without the editing problem that
// justifies it, so they stay single-file. Re-measure with
// `plugins/workflow/skills/ship-issue/plan-lens.sh` before enrolling another.
//
// Each artifact's fragments live in a `workflow.src/` sibling directory, so an
// installed plugin carries its own sources and stays regenerable.
const ENROLLED = [
  "plugins/workflow/skills/ship-issue/workflow.js",
  "plugins/review-audit/skills/codebase-audit/workflow.js",
];

const SRC_DIR_SUFFIX = "workflow.src";
const MANIFEST_NAME = "manifest.txt";

// Where a harness's fragments and manifest live.
const srcDirFor = (artifactRel) => join(repoRoot, dirname(artifactRel), SRC_DIR_SUFFIX);

// Parse an ordered fragment manifest: one filename per line, `#` comments and
// blank lines ignored. Returns names in file order — that order IS the
// concatenation order, which is why this never sorts.
function readManifest(srcDir) {
  const manifestPath = join(srcDir, MANIFEST_NAME);
  let raw;
  try {
    raw = readFileSync(manifestPath, "utf8");
  } catch {
    throw new Error(`missing fragment manifest: ${manifestPath}`);
  }
  const names = raw
    .split("\n")
    .map((line) => line.replace(/#.*$/, "").trim())
    .filter(Boolean);
  if (names.length === 0) {
    // A manifest that parses to nothing would concatenate to an empty artifact
    // and, on --check against an equally empty file, report a clean pass having
    // asserted nothing. Refuse it as the configuration error it is.
    throw new Error(`fragment manifest lists no fragments: ${manifestPath}`);
  }
  return names;
}

// Assert the listed set and the on-disk set are the same set, reporting BOTH
// directions. A listed-but-missing fragment is the obvious failure; an
// unlisted-on-disk one is the dangerous one, because it is a fragment someone
// wrote and edits believing it ships, while the artifact never contains a byte
// of it. Neither may pass quietly (AC1).
function assertFragmentSetMatches(srcDir, listed) {
  let onDisk;
  try {
    onDisk = readdirSync(srcDir).filter((n) => n.endsWith(".js")).sort();
  } catch {
    throw new Error(`missing fragment directory: ${srcDir}`);
  }

  const listedSet = new Set(listed);
  const problems = [];

  const duplicates = listed.filter((n, i) => listed.indexOf(n) !== i);
  for (const name of new Set(duplicates)) {
    problems.push(`fragment listed more than once in ${MANIFEST_NAME}: ${name}`);
  }
  for (const name of listed) {
    if (!onDisk.includes(name)) {
      problems.push(`fragment listed in ${MANIFEST_NAME} but missing on disk: ${name}`);
    }
  }
  for (const name of onDisk) {
    if (!listedSet.has(name)) {
      problems.push(`fragment on disk but unlisted in ${MANIFEST_NAME}: ${name}`);
    }
  }

  if (problems.length > 0) {
    throw new Error(`${srcDir}:\n  ${problems.join("\n  ")}`);
  }
}

// Build the artifact bytes for one harness. Pure concatenation in manifest
// order — see the header on why nothing here transforms the fragment contents.
export function renderArtifact(artifactRel) {
  const srcDir = srcDirFor(artifactRel);
  const listed = readManifest(srcDir);
  assertFragmentSetMatches(srcDir, listed);
  return listed.map((name) => readFileSync(join(srcDir, name), "utf8")).join("");
}

// Resolve a user-supplied harness argument against ENROLLED. Accepts the full
// artifact path or the containing skill/agent directory name, so both
// `plugins/workflow/skills/ship-issue/workflow.js` and `ship-issue` work.
function resolveHarnessArg(arg) {
  const matches = ENROLLED.filter(
    (rel) => rel === arg || dirname(rel).endsWith(`/${arg}`),
  );
  if (matches.length !== 1) {
    throw new Error(
      `not an enrolled harness: ${arg}\n  enrolled:\n    ${ENROLLED.join("\n    ")}`,
    );
  }
  return matches[0];
}

function main(argv) {
  const check = argv.includes("--check");
  const rest = argv.filter((a) => a !== "--check");

  const unknownFlags = rest.filter((a) => a.startsWith("-"));
  if (unknownFlags.length > 0) {
    process.stderr.write(`generate-workflow-js: unknown flag(s): ${unknownFlags.join(", ")}\n`);
    return 2;
  }

  let targets;
  try {
    targets = rest.length > 0 ? rest.map(resolveHarnessArg) : ENROLLED;
  } catch (err) {
    process.stderr.write(`generate-workflow-js: ${err.message}\n`);
    return 2;
  }

  let failed = 0;
  for (const rel of targets) {
    const artifactPath = join(repoRoot, rel);
    let rendered;
    try {
      rendered = renderArtifact(rel);
    } catch (err) {
      process.stderr.write(`generate-workflow-js: ${err.message}\n`);
      failed += 1;
      continue;
    }

    if (check) {
      let current;
      try {
        current = readFileSync(artifactPath, "utf8");
      } catch {
        process.stderr.write(`generate-workflow-js: missing artifact: ${rel}\n`);
        failed += 1;
        continue;
      }
      if (current !== rendered) {
        process.stderr.write(
          `generate-workflow-js: STALE artifact: ${rel}\n` +
            `  it does not match its fragments in ${dirname(rel)}/${SRC_DIR_SUFFIX}/.\n` +
            `  Edit the FRAGMENT, then regenerate: just gen-workflow-js\n`,
        );
        failed += 1;
        continue;
      }
      process.stdout.write(`ok  ${rel}\n`);
    } else {
      writeFileSync(artifactPath, rendered);
      process.stdout.write(`generated  ${rel}\n`);
    }
  }

  return failed > 0 ? 1 : 0;
}

process.exit(main(process.argv.slice(2)));
