#!/usr/bin/env python3
"""check-decomposition — Deterministic Pre-Scan (Python primary implementation).

Sizing + language-aware segmentation. Replaces the production-LOC counting prose
that was duplicated across audit-code-health, audit-architecture and
audit-ai-config (issue #663) with one deterministic implementation, and turns the
result from a line count into an actionable **decomposition seam**.

Python 3.11+ primary implementation behind the language-agnostic TSV contract;
the sibling patterns.sh is the portable bash fallback (it exec's this file when a
python3>=3.11 is present). Both emit byte-identical findings — the parity is
pinned by tests/validate-python-ports.sh and the behavior by
tests/validate-decomposition-detectors.sh. See CLAUDE.md § Key conventions.

Input:  argv[1] = file containing paths to scan (one per line)
Output: TSV to stdout: file<TAB>line<TAB>category<TAB>evidence<TAB>certainty

The 5-column contract is NOT widened. A seam is a per-file SPAN, so `line`
carries the seam START and the end line, unit names, fan-in and proposed target
path are encoded as structured text inside `evidence`:

    src/parser.rs<TAB>412<TAB>decomposition-seam<TAB>seam 412-680: fn parse_* \
family (6 units, fan-in 1 <- parse_entry) -> src/parser/parse.rs<TAB>HIGH

Every other check-* skill and all three parity gates keep the contract they have.
The audit-decomposition agent parses this evidence into line_start/line_end.

Thresholds are env-overridable (DECOMP_*, plus the CLAUDE_MD_*/SKILL_*/AGENT_*/
DOC_* bloat vars inherited from check-ai-config when the bloat table moved here).

Exit codes:
  0 = success (zero or more findings)
  1 = usage error (missing argument) or file list not found
"""

