def scan_file(path: str, lines: list[str]) -> None:
    lang = lang_of(path)
    units = find_units(lines, lang)
    m = measure(lines, lang, units)

    warn = _int_env("DECOMP_LOC_WARN", 300)
    high = _int_env("DECOMP_LOC_HIGH", 500)
    seam_min_units = _int_env("DECOMP_SEAM_MIN_UNITS", 3)
    seam_min_lines = _int_env("DECOMP_SEAM_MIN_LINES", 40)
    seam_max_fanin = _int_env("DECOMP_SEAM_MAX_FANIN", 3)
    god_units = _int_env("DECOMP_GOD_UNITS", 12)
    god_concerns = _int_env("DECOMP_GOD_CONCERNS", 3)
    cohesive_max_units = _int_env("DECOMP_COHESIVE_MAX_UNITS", 2)

    metrics = (
        "%d total, %d comment (%d%%), %d blank, %d test-excluded, "
        "max nesting %d, %d top-level units"
        % (
            m["total"],
            m["comment"],
            m["comment_pct"],
            m["blank"],
            m["test_excluded"],
            m["max_depth"],
            m["units"],
        )
    )

    # --- Size verdict: EXACTLY ONE per file (#701) -------------------------
    # A classified file gets its per-type budget and NOT the generic
    # production-LOC one: bloat_spec() returning a spec IS the statement "this
    # file type has its own budget", and applying the code thresholds on top
    # contradicts it. Before #701 both ran, so classified markdown produced two
    # rows for one problem (two categories, two different numbers), and a docs
    # page UNDER its own doc_md budget was still flagged at the 300 code
    # threshold — a threshold calibrated against a different meaning of "line"
    # (markdown has no comment/test exclusion, so production LOC degenerates
    # into "lines minus blanks").
    #
    # `over` is set by whichever branch fires, NOT by file-length alone: it
    # drives the reasoned-decline emit below, which is what backs
    # audit-decomposition.md's "every size finding pairs with a seam or a
    # recorded decline" contract. Keying it to one branch would silently drop
    # the decline for every classified file.
    over = False
    spec = bloat_spec(path)
    if spec is not None:
        # Per-type budget, measured on TOTAL lines — the deliberate choice
        # recorded in thresholds.yml § bloat_thresholds (#701).
        b_warn, b_high, ftype, category = spec
        n = m["total"]
        if n > b_high:
            over = True
            emit(
                path,
                1,
                category,
                "%s exceeds high threshold: %d lines (>%d)" % (ftype, n, b_high),
                "HIGH",
            )
        elif n > b_warn:
            over = True
            emit(
                path,
                1,
                category,
                "%s exceeds warning threshold: %d lines (>%d)" % (ftype, n, b_warn),
                "MEDIUM",
            )
    elif m["production"] > high:
        over = True
        emit(
            path,
            1,
            "file-length",
            "%d production LOC (>%d high); %s" % (m["production"], high, metrics),
            "HIGH",
        )
    elif m["production"] > warn:
        over = True
        emit(
            path,
            1,
            "file-length",
            "%d production LOC (>%d warning); %s" % (m["production"], warn, metrics),
            "MEDIUM",
        )

    # --- Bundle-aware split guidance (#700) --------------------------------
    # A memory bundle gets its OWN split shape, and the generic markdown
    # heading-cluster seam is SUPPRESSED for it — the same one-verdict move
    # #701 made for size, applied to the seam. Emitting a `seam 40-96:` row for
    # an index would be actively wrong guidance: an index splits by TOPIC
    # CLUSTER, not by line range, and a concept split that does not also add an
    # index line silently orphans the extracted half (#669's `memory-orphan`,
    # the never-recalled failure).
    #
    # Gated on `over`, so a bundle file inside its budget emits NOTHING.
    kind = bundle_kind(path)
    if kind:
        if over:
            names = bundle_sections(lines)
            if kind == "index":
                if len(names) >= 2:
                    emit(
                        path,
                        1,
                        "decomposition-seam",
                        "index split: %d topic clusters (%s) -> index-<topic>.md; "
                        "root keeps one pointer line per sub-index"
                        % (len(names), ", ".join(names[:5])),
                        "HIGH",
                    )
                else:
                    emit(
                        path,
                        1,
                        "decomposition-seam",
                        "declined: index has no topic clusters to split on "
                        "(%d sections) — trim entries instead" % len(names),
                        "LOW",
                    )
            elif len(names) >= 2:
                # Two lessons in one file: extract the second, and REQUIRE its
                # index line in the same breath.
                emit(
                    path,
                    1,
                    "decomposition-seam",
                    "concept split: extract %s to %s/%s.md AND add its index "
                    "line (an extracted concept with no index line is an orphan)"
                    % (names[1], concept_dir(path), names[1]),
                    "HIGH",
                )
            else:
                emit(
                    path,
                    1,
                    "decomposition-seam",
                    "declined: single lesson — no second concept to extract "
                    "(%d sections); tighten the prose instead" % len(names),
                    "LOW",
                )
        return

    if not lang:
        return

    clusters = cluster_units(units)
    prefixes = []
    for c in clusters:
        if c.prefix not in prefixes:
            prefixes.append(c.prefix)

    # --- Category: god-module ---------------------------------------------
    # Size alone is not a god module. The signal is size AND many top-level
    # units AND several distinct concerns — the coupling half stays with
    # audit-architecture, which now consumes this LOC number instead of
    # re-deriving it from its own copy of the counting rules.
    if (
        m["production"] > warn
        and m["units"] > god_units
        and len(prefixes) >= god_concerns
    ):
        emit(
            path,
            1,
            "god-module",
            "%d production LOC, %d top-level units, %d concerns (%s)"
            % (
                m["production"],
                m["units"],
                len(prefixes),
                ", ".join(prefixes[:5]),
            ),
            "MEDIUM",
        )

    # --- Category: decomposition-seam --------------------------------------
    noun = UNIT_NOUN.get(lang, "unit")
    seams = 0
    # A .d.ts holds no runtime code to extract (#726), so it yields no seam —
    # and, because the shape row below is gated on `seams > 0`, no shape row
    # either. It still falls through to the reasoned decline, which is the
    # point: a declaration file is EXAMINED and found unsplittable, not skipped.
    # Silence would be indistinguishable from "not scanned".
    for c in [] if is_decl_file(path) else clusters:
        span = c.end - c.start + 1
        if len(c.units) < seam_min_units or span < seam_min_lines:
            continue
        count, callers = fan_in(lines, c, units)
        if count == 0:
            fan = "no external references"
        elif count <= seam_max_fanin and callers:
            fan = "fan-in %d <- %s" % (count, callers)
        else:
            fan = "fan-in %d" % count
        emit(
            path,
            c.start,
            "decomposition-seam",
            "seam %d-%d: %s %s_* family (%d units, %s) -> %s"
            % (
                c.start,
                c.end,
                noun,
                c.prefix,
                len(c.units),
                fan,
                target_path(path, c.prefix),
            ),
            "HIGH",
        )
        seams += 1

    # --- The split SHAPE (#725) --------------------------------------------
    # The seam rows above say WHERE to cut. This says what the result should
    # LOOK LIKE — a package dir, a barrel index, a sourced fragment. Without it
    # the audit lens hands a backlog reader a bare line range weeks after the
    # sweep, with none of the PR context that would make it interpretable; the
    # review lens, whose reader has the diff on screen, had the better guidance.
    #
    # Gated on `seams > 0`, NOT merely `over`. The `over and seams == 0` arm
    # below emits a reasoned decline — "no low-coupling seam found", "single
    # cohesive unit" — and a shape row beside it would contradict its own
    # neighbour, telling the reader to build a package dir out of a file the
    # scanner just said has nothing to cut. Shape accompanies a real seam; a
    # decline stands alone. (Same one-verdict discipline as #700's bundle
    # suppression, applied to the language path.)
    #
    # Unreachable for a memory bundle by CONSTRUCTION: the bundle branch above
    # returns before this point, so an index/concept never receives generic md
    # advice. Fixtured anyway — an invariant that holds by construction is one
    # refactor away from not holding.
    # `lang` is non-empty here — the `if not lang: return` above this point
    # guarantees it — so SPLIT_SHAPE_FALLBACK is UNREACHABLE in this lens, and
    # deliberately so rather than untested: only the review lens sizes a file
    # with no segmenter (.rb, .java, .c), because only it is handed an arbitrary
    # diff. Recorded here rather than given a test that cannot fail
    # ([[surviving-mutation-may-be-a-real-no-op]]); the fallback IS exercised,
    # through sizing.py, by tests/validate-sizing-scanner.sh's
    # test_unknown_language_still_emits_a_seam_row (named, so the claim is
    # checkable rather than a cross-file assertion the reader must take on
    # trust). If a language is ever added to EXT_LANG without a segmenter, the
    # invariant behind "unreachable" breaks — and the shape/segmenter key-set
    # test in validate-shared-scanner-sync.sh is what fails first.
    if seams > 0:
        emit(
            path,
            1,
            "decomposition-seam",
            "split shape for %s: %s" % (lang, split_shape(lang)),
            "MEDIUM",
        )

    # --- Reasoned decline --------------------------------------------------
    # A file over threshold with no seam is a RESULT, not a silence. A generated
    # artifact, a lookup table, one exhaustive match — long and correct. Record
    # why, so "no seam" can never be mistaken for "not examined"; the finding
    # carries the reason into the baseline= acknowledgment.
    if over and seams == 0:
        generated = any(GENERATED_RE.search(ln) for ln in lines[:20])
        # Ahead of `generated` on purpose (#726): a .d.ts is very often ALSO
        # banner-marked as generated, and "type declaration file" is the more
        # specific fact — it explains why there is nothing to extract even for a
        # hand-maintained one, which the generated reason does not.
        if is_decl_file(path):
            reason = "type declaration file — no runtime units to extract"
        elif generated:
            reason = "generated file — regenerate rather than split"
        elif m["units"] <= cohesive_max_units:
            reason = "single cohesive unit — no internal seam to cut"
        elif m["comment_pct"] >= 50:
            reason = "majority prose/comment — length is documentation, not logic"
        else:
            reason = "no low-coupling seam found — units are mutually referential"
        emit(
            path,
            1,
            "decomposition-seam",
            "declined: %s (%d production LOC, %d top-level units)"
            % (reason, m["production"], m["units"]),
            "LOW",
        )


def main(argv: list[str]) -> int:
    if len(argv) < 2 or not argv[1]:
        sys.stderr.write("Usage: patterns.py <file-list>\n")
        return 1

    file_list = argv[1]
    try:
        with open(file_list, "r", encoding="utf-8", errors="replace") as fh:
            paths = [ln.rstrip("\n") for ln in fh]
    except OSError:
        sys.stderr.write("Error: file list not found: " + file_list + "\n")
        return 1

    for path in paths:
        if not path:
            continue
        try:
            with open(path, "r", encoding="utf-8", errors="replace") as fh:
                lines = fh.read().splitlines()
        except OSError:
            continue
        if any(_fnmatch.fnmatchcase(path, g) for g in SKIP_GLOBS):
            continue
        scan_file(path, lines)

    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
