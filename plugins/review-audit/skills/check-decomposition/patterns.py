class Cluster:
    """A maximal run of CONSECUTIVE same-family units — contiguous by
    construction, which is what makes the span a single mechanical move."""

    __slots__ = ("prefix", "units", "start", "end")

    def __init__(self, prefix: str, units: list[Unit]) -> None:
        self.prefix = prefix
        self.units = units
        self.start = units[0].start
        self.end = units[-1].end


def cluster_units(units: list[Unit]) -> list[Cluster]:
    """Group ADJACENT units sharing a family prefix.

    Adjacency is by unit INDEX, not merely by same-prefix order: a test unit (or
    any other family) sitting between two same-family units breaks the run. That
    matters because the span is meant to be a single mechanical move — a
    `render_*` trio interleaved with eight test functions spans 230 lines that
    cannot be lifted out without dragging the tests along, so it is not a seam.
    """
    clusters: list[Cluster] = []
    run: list[Unit] = []
    last_idx = -2
    for idx, u in enumerate(units):
        if u.is_test:
            continue
        if run and run[-1].prefix == u.prefix and idx == last_idx + 1:
            run.append(u)
        else:
            if run:
                clusters.append(Cluster(run[0].prefix, run))
            run = [u]
        last_idx = idx
    if run:
        clusters.append(Cluster(run[0].prefix, run))
    return clusters


def fan_in(lines: list[str], cluster: Cluster, units: list[Unit]) -> tuple[int, str]:
    """How much of the REST of the file reaches into this cluster.

    Returns (reference count, comma-joined names of the referencing top-level
    units, capped at 3). A low fan-in is the signal that the span is a
    low-coupling cut point — the whole point of naming a seam rather than a size.
    """
    names = set(u.name for u in cluster.units)
    count = 0
    callers: list[str] = []
    for idx, line in enumerate(lines, start=1):
        if cluster.start <= idx <= cluster.end:
            continue
        if not (names & set(TOKEN_RE.findall(line))):
            continue
        count += 1
        for u in units:
            if u.start <= idx <= u.end and u.name not in callers:
                callers.append(u.name)
                break
    callers.sort()
    return count, ", ".join(callers[:3])


def target_path(path: str, prefix: str) -> str:
    """Where the seam should move to: a sibling module named for the family,
    under a directory named for the file it came from."""
    if "/" in path:
        directory, base = path.rsplit("/", 1)
    else:
        directory, base = "", path
    stem, dot, ext = base.rpartition(".")
    if not dot:
        stem, ext = base, ""
    suffix = ("." + ext) if ext else ""
    inner = stem + "/" + prefix + suffix
    return (directory + "/" + inner) if directory else inner


def concept_dir(path: str) -> str:
    """Which directory an extracted memory-bundle concept belongs in (#713).

    The source file's OWN directory, not the bundle root. `bundle_kind()`
    explicitly supports a concept nested below the root (its `*/root/*` arm), and
    for `<root>/topics/two-lessons.md` a root-anchored target silently drops the
    `topics/` segment — advice that, followed literally, moves the extracted
    lesson out of its subdirectory instead of alongside the sibling it was
    extracted from. Deriving from the source path is what every other
    seam-target computation here does (`target_path()`).

    Deliberately NOT `target_path()` itself, which builds `dir/stem/prefix.ext`
    — a subdirectory named for the source file. That is right for a code family
    and wrong for a bundle: an extracted lesson is a flat SIBLING of the file it
    came from, never a child of it.

    A flat-bundle file already HAS the root as its own directory, so the common
    case is unchanged by this derivation — only a nested concept moves. The
    bundle-root fallback is therefore defensive and unreachable from the only
    call site: `bundle_kind()` sets a kind only for a path matching
    `<root>/...` or `.../<root>/...`, both of which contain a slash."""
    if "/" in path:
        return path.rsplit("/", 1)[0]
    return _bundle_root()


def _bundle_root() -> str:
    """The configured memory-bundle root, normalized for glob matching (#700).

    Configurable rather than hardcoded, defaulting to `.claude/memory`. An
    EMPTY value means no bundle is configured: memory classification is off and
    nothing errors.

    Normalization strips a leading `./` and any trailing `/` so that every
    spelling of the same root — `.claude/memory`, `./.claude/memory`,
    `.claude/memory/` — decides alike. An unnormalized root would make the
    glob miss, the file would fall back to the code thresholds, and the scan
    would still exit 0 — the silent fail-open this issue exists to close."""
    root = os.environ.get("MEMORY_BUNDLE_ROOT", ".claude/memory").strip()
    while root.startswith("./"):
        root = root[2:]
    while root.endswith("/"):
        root = root[:-1]
    return root


def bundle_kind(path: str) -> str:
    """Which half of the memory bundle PATH is: "index", "concept", or "" when
    it is not a bundle markdown file (#700).

    Only `*.md` under the root is bundle prose — a `.sh` or `.py` sitting in a
    bundle is code and keeps the code thresholds.

    An index is the file loaded every session to route recall: the root
    `MEMORY.md`, a topic sub-index `index-*.md`, or OKF's `index.md`."""
    root = _bundle_root()
    if not root:
        return ""
    # LITERAL containment, deliberately NOT _glob(). The root is operator
    # configuration, and routing it through fnmatch would interpret any glob
    # metacharacter in it (`[`, `]`, `*`, `?`) as syntax. The bash mirror does
    # NOT: a QUOTED expansion in a `case` pattern (`"$MEMORY_BUNDLE_ROOT"/*.md`)
    # is matched literally by bash. So a root like `weird[x]root` made fnmatch
    # read `[x]` as a character class and miss, while bash matched — the two
    # impls disagreed on the same file, breaking the byte-identical TSV
    # contract, silently and at exit 0. These two tests mirror bash's two arms:
    # `"$ROOT"/*` (root at the start) and `*/"$ROOT"/*` (root nested anywhere).
    if not (path.startswith(root + "/") or ("/" + root + "/") in path):
        return ""
    base = path.rsplit("/", 1)[-1]
    if not base.endswith(".md"):
        return ""
    if base == "MEMORY.md" or base == "index.md" or base.startswith("index-"):
        return "index"
    return "concept"


def bundle_sections(lines: list[str]) -> list[str]:
    """The topic clusters of a bundle markdown file (#700).

    NOT the same as `find_units`' top-level units. `find_units` takes the
    SHALLOWEST heading depth present, which for a normal bundle file is the
    lone `# Title` — so the `##` topic sections, which are exactly what an
    index splits along, would be invisible and every index would decline.

    The rule here is the shallowest depth that has at least TWO headings: a
    `# Title` + `## topics` file clusters by its `##`, and a file written with
    all-`##` sections and no title clusters by those same `##`. Falls back to
    the shallowest depth when nothing repeats (a genuinely unsplittable file)."""
    heads: list[tuple[int, str]] = []
    fenced = False
    for line in lines:
        if line.startswith("```") or line.startswith("~~~"):
            fenced = not fenced
            continue
        if fenced:
            continue
        m = re.match(r"^(#{1,6})[ \t]+(.*)$", line)
        if m:
            heads.append((len(m.group(1)), md_slug(m.group(2)) or "section"))
    if not heads:
        return []
    depths = sorted(set(d for d, _ in heads))
    chosen = depths[0]
    for d in depths:
        if sum(1 for hd, _ in heads if hd == d) >= 2:
            chosen = d
            break
    return [name for d, name in heads if d == chosen]


def bloat_spec(path: str) -> tuple[int, int, str, str] | None:
    """The per-file-type bloat thresholds, migrated verbatim from
    check-ai-config so the move is behavior-preserving. Returns
    (warn, high, file-type label, category) or None when the path is not an
    AI-instruction or documentation file.

    The memory-bundle arm is FIRST (#700): inside a configured bundle, bundle
    rules apply, so a `docs/` or `agents/` directory nested in the bundle
    cannot escape to the arms below and be sized by the wrong budget."""
    kind = bundle_kind(path)
    if kind == "index":
        return (
            _int_env("MEMORY_INDEX_WARN", 150),
            _int_env("MEMORY_INDEX_HIGH", 250),
            "memory index",
            "ai-file-bloat",
        )
    if kind == "concept":
        return (
            _int_env("MEMORY_CONCEPT_WARN", 200),
            _int_env("MEMORY_CONCEPT_HIGH", 350),
            "memory concept",
            "ai-file-bloat",
        )
    if _glob(path, "*/CLAUDE.md") or _glob(path, "*/AGENTS.md"):
        return (
            _int_env("CLAUDE_MD_WARN", 400),
            _int_env("CLAUDE_MD_HIGH", 600),
            "CLAUDE.md",
            "ai-file-bloat",
        )
    if _glob(path, "*/skills/*/SKILL.md"):
        return (
            _int_env("SKILL_WARN", 300),
            _int_env("SKILL_HIGH", 500),
            "skill definition",
            "ai-file-bloat",
        )
    if _glob(path, "*/agents/*/*.md") or _glob(path, "*/agents/*.md"):
        # Both agent layouts: the FLAT agents/<name>.md Claude Code discovers,
        # and the nested agents/<name>/<name>.md a harness-bearing agent uses.
        return (
            _int_env("AGENT_WARN", 250),
            _int_env("AGENT_HIGH", 400),
            "agent definition",
            "ai-file-bloat",
        )
    if _glob(path, "*/skills/*/*.md"):
        # Skill COMPANION prose (#589) — a reference file a SKILL.md tells the
        # agent to load. MUST stay below the SKILL.md arm above, which is the
        # narrower pattern: these arms are sequential, so hoisting this one
        # would swallow every SKILL.md into the looser companion budget.
        #
        # Before this arm existed, a companion matched NOTHING here and fell
        # through to the production-LOC code thresholds (300/500) — sized by a
        # rule written for source. Exactly the defect #700 fixed for memory
        # bundles, on the repo's LARGEST prose files.
        return (
            _int_env("COMPANION_WARN", 400),
            _int_env("COMPANION_HIGH", 650),
            "skill companion",
            "ai-file-bloat",
        )
    if _glob(path, "*/docs/*.md"):
        return (
            _int_env("DOC_WARN", 500),
            _int_env("DOC_HIGH", 800),
            "documentation",
            "doc-file-bloat",
        )
    return None


def scan_file(path: str, lines: list[str]) -> None:
    lang = lang_of(path)
    units = find_units(lines, lang)
    m = measure(lines, lang, units)

    warn = _int_env("DECOMP_LOC_WARN", 300)
    high = _int_env("DECOMP_LOC_HIGH", 500)
    seam_min_units = _int_env("DECOMP_SEAM_MIN_UNITS", 3)
    seam_min_lines = _int_env("DECOMP_SEAM_MIN_LINES", 40)
    seam_max_fanin = _int_env("DECOMP_SEAM_MAX_FANIN", 3)
    god_units = _int_env("DECOMP_GOD_UNITS", 12)
    god_concerns = _int_env("DECOMP_GOD_CONCERNS", 3)
    cohesive_max_units = _int_env("DECOMP_COHESIVE_MAX_UNITS", 2)

    metrics = (
        "%d total, %d comment (%d%%), %d blank, %d test-excluded, "
        "max nesting %d, %d top-level units"
        % (
            m["total"],
            m["comment"],
            m["comment_pct"],
            m["blank"],
            m["test_excluded"],
            m["max_depth"],
            m["units"],
        )
    )

    # --- Size verdict: EXACTLY ONE per file (#701) -------------------------
    # A classified file gets its per-type budget and NOT the generic
    # production-LOC one: bloat_spec() returning a spec IS the statement "this
    # file type has its own budget", and applying the code thresholds on top
    # contradicts it. Before #701 both ran, so classified markdown produced two
    # rows for one problem (two categories, two different numbers), and a docs
    # page UNDER its own doc_md budget was still flagged at the 300 code
    # threshold — a threshold calibrated against a different meaning of "line"
    # (markdown has no comment/test exclusion, so production LOC degenerates
    # into "lines minus blanks").
    #
    # `over` is set by whichever branch fires, NOT by file-length alone: it
    # drives the reasoned-decline emit below, which is what backs
    # audit-decomposition.md's "every size finding pairs with a seam or a
    # recorded decline" contract. Keying it to one branch would silently drop
    # the decline for every classified file.
    over = False
    spec = bloat_spec(path)
    if spec is not None:
        # Per-type budget, measured on TOTAL lines — the deliberate choice
        # recorded in thresholds.yml § bloat_thresholds (#701).
        b_warn, b_high, ftype, category = spec
        n = m["total"]
        if n > b_high:
            over = True
            emit(
                path,
                1,
                category,
                "%s exceeds high threshold: %d lines (>%d)" % (ftype, n, b_high),
                "HIGH",
            )
        elif n > b_warn:
            over = True
            emit(
                path,
                1,
                category,
                "%s exceeds warning threshold: %d lines (>%d)" % (ftype, n, b_warn),
                "MEDIUM",
            )
    elif m["production"] > high:
        over = True
        emit(
            path,
            1,
            "file-length",
            "%d production LOC (>%d high); %s" % (m["production"], high, metrics),
            "HIGH",
        )
    elif m["production"] > warn:
        over = True
        emit(
            path,
            1,
            "file-length",
            "%d production LOC (>%d warning); %s" % (m["production"], warn, metrics),
            "MEDIUM",
        )

    # --- Bundle-aware split guidance (#700) --------------------------------
    # A memory bundle gets its OWN split shape, and the generic markdown
    # heading-cluster seam is SUPPRESSED for it — the same one-verdict move
    # #701 made for size, applied to the seam. Emitting a `seam 40-96:` row for
    # an index would be actively wrong guidance: an index splits by TOPIC
    # CLUSTER, not by line range, and a concept split that does not also add an
    # index line silently orphans the extracted half (#669's `memory-orphan`,
    # the never-recalled failure).
    #
    # Gated on `over`, so a bundle file inside its budget emits NOTHING.
    kind = bundle_kind(path)
    if kind:
        if over:
            names = bundle_sections(lines)
            if kind == "index":
                if len(names) >= 2:
                    emit(
                        path,
                        1,
                        "decomposition-seam",
                        "index split: %d topic clusters (%s) -> index-<topic>.md; "
                        "root keeps one pointer line per sub-index"
                        % (len(names), ", ".join(names[:5])),
                        "HIGH",
                    )
                else:
                    emit(
                        path,
                        1,
                        "decomposition-seam",
                        "declined: index has no topic clusters to split on "
                        "(%d sections) — trim entries instead" % len(names),
                        "LOW",
                    )
            elif len(names) >= 2:
                # Two lessons in one file: extract the second, and REQUIRE its
                # index line in the same breath.
                emit(
                    path,
                    1,
                    "decomposition-seam",
                    "concept split: extract %s to %s/%s.md AND add its index "
                    "line (an extracted concept with no index line is an orphan)"
                    % (names[1], concept_dir(path), names[1]),
                    "HIGH",
                )
            else:
                emit(
                    path,
                    1,
                    "decomposition-seam",
                    "declined: single lesson — no second concept to extract "
                    "(%d sections); tighten the prose instead" % len(names),
                    "LOW",
                )
        return

    if not lang:
        return

    clusters = cluster_units(units)
    prefixes = []
    for c in clusters:
        if c.prefix not in prefixes:
            prefixes.append(c.prefix)

    # --- Category: god-module ---------------------------------------------
    # Size alone is not a god module. The signal is size AND many top-level
    # units AND several distinct concerns — the coupling half stays with
    # audit-architecture, which now consumes this LOC number instead of
    # re-deriving it from its own copy of the counting rules.
    if (
        m["production"] > warn
        and m["units"] > god_units
        and len(prefixes) >= god_concerns
    ):
        emit(
            path,
            1,
            "god-module",
            "%d production LOC, %d top-level units, %d concerns (%s)"
            % (
                m["production"],
                m["units"],
                len(prefixes),
                ", ".join(prefixes[:5]),
            ),
            "MEDIUM",
        )

    # --- Category: decomposition-seam --------------------------------------
    noun = UNIT_NOUN.get(lang, "unit")
    seams = 0
    for c in clusters:
        span = c.end - c.start + 1
        if len(c.units) < seam_min_units or span < seam_min_lines:
            continue
        count, callers = fan_in(lines, c, units)
        if count == 0:
            fan = "no external references"
        elif count <= seam_max_fanin and callers:
            fan = "fan-in %d <- %s" % (count, callers)
        else:
            fan = "fan-in %d" % count
        emit(
            path,
            c.start,
            "decomposition-seam",
            "seam %d-%d: %s %s_* family (%d units, %s) -> %s"
            % (
                c.start,
                c.end,
                noun,
                c.prefix,
                len(c.units),
                fan,
                target_path(path, c.prefix),
            ),
            "HIGH",
        )
        seams += 1

    # --- Reasoned decline --------------------------------------------------
    # A file over threshold with no seam is a RESULT, not a silence. A generated
    # artifact, a lookup table, one exhaustive match — long and correct. Record
    # why, so "no seam" can never be mistaken for "not examined"; the finding
    # carries the reason into the baseline= acknowledgment.
    if over and seams == 0:
        generated = any(GENERATED_RE.search(ln) for ln in lines[:20])
        if generated:
            reason = "generated file — regenerate rather than split"
        elif m["units"] <= cohesive_max_units:
            reason = "single cohesive unit — no internal seam to cut"
        elif m["comment_pct"] >= 50:
            reason = "majority prose/comment — length is documentation, not logic"
        else:
            reason = "no low-coupling seam found — units are mutually referential"
        emit(
            path,
            1,
            "decomposition-seam",
            "declined: %s (%d production LOC, %d top-level units)"
            % (reason, m["production"], m["units"]),
            "LOW",
        )


def main(argv: list[str]) -> int:
    if len(argv) < 2 or not argv[1]:
        sys.stderr.write("Usage: patterns.py <file-list>\n")
        return 1

    file_list = argv[1]
    try:
        with open(file_list, "r", encoding="utf-8", errors="replace") as fh:
            paths = [ln.rstrip("\n") for ln in fh]
    except OSError:
        sys.stderr.write("Error: file list not found: " + file_list + "\n")
        return 1

    for path in paths:
        if not path:
            continue
        try:
            with open(path, "r", encoding="utf-8", errors="replace") as fh:
                lines = fh.read().splitlines()
        except OSError:
            continue
        if any(_fnmatch.fnmatchcase(path, g) for g in SKIP_GLOBS):
            continue
        scan_file(path, lines)

    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
