class Cluster:
    """A maximal run of CONSECUTIVE same-family units — contiguous by
    construction, which is what makes the span a single mechanical move."""

    __slots__ = ("prefix", "units", "start", "end")

    def __init__(self, prefix: str, units: list[Unit]) -> None:
        self.prefix = prefix
        self.units = units
        self.start = units[0].start
        self.end = units[-1].end


def cluster_units(units: list[Unit]) -> list[Cluster]:
    """Group ADJACENT units sharing a family prefix.

    Adjacency is by unit INDEX, not merely by same-prefix order: a test unit (or
    any other family) sitting between two same-family units breaks the run. That
    matters because the span is meant to be a single mechanical move — a
    `render_*` trio interleaved with eight test functions spans 230 lines that
    cannot be lifted out without dragging the tests along, so it is not a seam.
    """
    clusters: list[Cluster] = []
    run: list[Unit] = []
    last_idx = -2
    for idx, u in enumerate(units):
        if u.is_test:
            continue
        if run and run[-1].prefix == u.prefix and idx == last_idx + 1:
            run.append(u)
        else:
            if run:
                clusters.append(Cluster(run[0].prefix, run))
            run = [u]
        last_idx = idx
    if run:
        clusters.append(Cluster(run[0].prefix, run))
    return clusters


def fan_in(lines: list[str], cluster: Cluster, units: list[Unit]) -> tuple[int, str]:
    """How much of the REST of the file reaches into this cluster.

    Returns (reference count, comma-joined names of the referencing top-level
    units, capped at 3). A low fan-in is the signal that the span is a
    low-coupling cut point — the whole point of naming a seam rather than a size.
    """
    names = set(u.name for u in cluster.units)
    count = 0
    callers: list[str] = []
    for idx, line in enumerate(lines, start=1):
        if cluster.start <= idx <= cluster.end:
            continue
        if not (names & set(TOKEN_RE.findall(line))):
            continue
        count += 1
        for u in units:
            if u.start <= idx <= u.end and u.name not in callers:
                callers.append(u.name)
                break
    callers.sort()
    return count, ", ".join(callers[:3])


def target_path(path: str, prefix: str) -> str:
    """Where the seam should move to: a sibling module named for the family,
    under a directory named for the file it came from."""
    if "/" in path:
        directory, base = path.rsplit("/", 1)
    else:
        directory, base = "", path
    stem, dot, ext = base.rpartition(".")
    if not dot:
        stem, ext = base, ""
    suffix = ("." + ext) if ext else ""
    inner = stem + "/" + prefix + suffix
    return (directory + "/" + inner) if directory else inner


def concept_dir(path: str) -> str:
    """Which directory an extracted memory-bundle concept belongs in (#713).

    The source file's OWN directory, not the bundle root. `bundle_kind()`
    explicitly supports a concept nested below the root (its `*/root/*` arm), and
    for `<root>/topics/two-lessons.md` a root-anchored target silently drops the
    `topics/` segment — advice that, followed literally, moves the extracted
    lesson out of its subdirectory instead of alongside the sibling it was
    extracted from. Deriving from the source path is what every other
    seam-target computation here does (`target_path()`).

    Deliberately NOT `target_path()` itself, which builds `dir/stem/prefix.ext`
    — a subdirectory named for the source file. That is right for a code family
    and wrong for a bundle: an extracted lesson is a flat SIBLING of the file it
    came from, never a child of it.

    A flat-bundle file already HAS the root as its own directory, so the common
    case is unchanged by this derivation — only a nested concept moves. The
    bundle-root fallback is therefore defensive and unreachable from the only
    call site: `bundle_kind()` sets a kind only for a path matching
    `<root>/...` or `.../<root>/...`, both of which contain a slash."""
    if "/" in path:
        return path.rsplit("/", 1)[0]
    return _bundle_root()


def bundle_sections(lines: list[str]) -> list[str]:
    """The topic clusters of a bundle markdown file (#700).

    NOT the same as `find_units`' top-level units. `find_units` takes the
    SHALLOWEST heading depth present, which for a normal bundle file is the
    lone `# Title` — so the `##` topic sections, which are exactly what an
    index splits along, would be invisible and every index would decline.

    The rule here is the shallowest depth that has at least TWO headings: a
    `# Title` + `## topics` file clusters by its `##`, and a file written with
    all-`##` sections and no title clusters by those same `##`. Falls back to
    the shallowest depth when nothing repeats (a genuinely unsplittable file)."""
    heads: list[tuple[int, str]] = []
    fenced = False
    for line in lines:
        if line.startswith("```") or line.startswith("~~~"):
            fenced = not fenced
            continue
        if fenced:
            continue
        m = re.match(r"^(#{1,6})[ \t]+(.*)$", line)
        if m:
            heads.append((len(m.group(1)), md_slug(m.group(2)) or "section"))
    if not heads:
        return []
    depths = sorted(set(d for d, _ in heads))
    chosen = depths[0]
    for d in depths:
        if sum(1 for hd, _ in heads if hd == d) >= 2:
            chosen = d
            break
    return [name for d, name in heads if d == chosen]


